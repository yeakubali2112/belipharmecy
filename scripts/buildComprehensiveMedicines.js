// Enrich existing medicines with nameBn, genericBn, and keywords
const enrichedExisting = existingMedicines.map(med => {
  const nameLower = (med.name || '').toLowerCase().trim();
  const nameBn = med.nameBn || NAME_BN_LOOKUP[nameLower] || NAME_BN_LOOKUP[nameLower.split(' ')[0]] || '';
  const genericBn = med.genericBn || getGenericBn(med.generic);
  const keywords = generateKeywords(med.name, nameBn, med.generic, genericBn, med.company, med.category, med.indications);
  return {
    ...med,
    nameBn: nameBn || med.name,
    genericBn: genericBn || med.generic,
    keywords: Array.from(new Set([...(med.keywords || []), ...keywords]))
  };
});

// Create new medicine objects with unique IDs
let nextIdNum = 200;
const enrichedNew = NEW_BANGLADESH_MEDICINES.map(med => {
  const id = `med-${nextIdNum++}`;
  const genericBn = med.genericBn || getGenericBn(med.generic);
  const keywords = generateKeywords(med.name, med.nameBn, med.generic, genericBn, med.company, med.category, med.indications);
  return {
    id,
    ...med,
    genericBn,
    keywords,
    dosage: med.dosage || 'চিকিৎসকের পরামর্শ অনুযায়ী সেব্য।',
    sideEffects: med.sideEffects || 'সাধারণত মৃদু ও সহনীয়।'
  };
});

// Check if any new medicine already exists by name to avoid duplicates
const existingNameSet = new Set(enrichedExisting.map(m => m.name.toLowerCase().trim()));
const trulyNew = enrichedNew.filter(m => !existingNameSet.has(m.name.toLowerCase().trim()));

const finalMedicinesList = [...enrichedExisting, ...trulyNew];

