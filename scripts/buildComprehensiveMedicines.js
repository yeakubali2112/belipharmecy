// Generate search keywords for medicine
function generateKeywords(name, nameBn, generic, genericBn, company, category, indications) {
  const set = new Set();
  if (name) name.toLowerCase().split(/[\s\-+]+/).forEach(w => w.length > 1 && set.add(w));
  if (nameBn) set.add(nameBn);
  if (generic) generic.toLowerCase().split(/[\s\-+,]+/).forEach(w => w.length > 2 && set.add(w));
  if (company) company.toLowerCase().split(/[\s\-+,]+/).forEach(w => w.length > 3 && set.add(w));
  
  // Symptoms & categories mapping
  const indicationsStr = (indications || '').toLowerCase();
  if (indicationsStr.includes('জ্বর') || (name && name.toLowerCase().includes('napa'))) {
    set.add('জ্বর'); set.add('fever'); set.add('paracetamol'); set.add('প্যারাসিটামল');
  }
  if (indicationsStr.includes('ব্যথা') || indicationsStr.includes('মাথা ব্যথা')) {
    set.add('ব্যথা'); set.add('pain'); set.add('মাথাব্যথা'); set.add('headache');
  }
  if (indicationsStr.includes('গ্যাস্ট্রিক') || category === 'gastric') {
    set.add('গ্যাস্ট্রিক'); set.add('gastric'); set.add('acidity'); set.add('এসিডিটি'); set.add('বুক জ্বালা');
  }
  if (indicationsStr.includes('কাশি') || indicationsStr.includes('ঠান্ডা') || category === 'respiratory') {
    set.add('কাশি'); set.add('cough'); set.add('ঠান্ডা'); set.add('সর্দি'); set.add('cold'); set.add('অ্যালার্জি'); set.add('allergy');
  }
  if (category === 'antibiotics') {
    set.add('অ্যান্টিবায়োটিক'); set.add('antibiotic'); set.add('সংক্রমণ');
  }
  if (category === 'diabetes') {
    set.add('ডায়াবেটিস'); set.add('diabetes'); set.add('sugar');
  }
  if (category === 'heart') {
    set.add('প্রেশার'); set.add('pressure'); set.add('bp'); set.add('হৃদরোগ');
  }
  if (category === 'vitamins') {
    set.add('ভিটামিন'); set.add('vitamin'); set.add('ক্যালসিয়াম'); set.add('calcium');
  }
  return Array.from(set);
}

